import fs from 'node:fs'
import path from 'node:path'
import { createRequire } from 'node:module'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const require = createRequire(import.meta.url)
const i18nRequire = createRequire(require.resolve('vue-i18n'))
const { baseCompile } = i18nRequire('@intlify/message-compiler')
const locales = {}
for (const locale of ['zh-CN', 'en-US']) {
  const messages = (await import(pathToFileURL(path.join(root, 'lang', `${locale}.js`)).href)).default
  const entries = []
  function visit(value, key = '') {
    if (typeof value === 'string') {
      const { code } = baseCompile(value, { mode: 'arrow', onError(error) { throw error } })
      entries.push(`  ${JSON.stringify(key)}: ${code}`)
    } else {
      for (const [name, child] of Object.entries(value)) visit(child, key ? `${key}.${name}` : name)
    }
  }
  visit(messages)
  locales[locale] = `{
${entries.join(',\n')}
}`
}
const output = `// Generated by node scripts/compile-mp-locales.mjs; regenerate after editing lang/*.js.
// Flat keys and precompiled functions work without runtime compilation in mini programs.
export default {
${Object.entries(locales).map(([locale, code]) => `  ${JSON.stringify(locale)}: ${code}`).join(',\n')}
}
`
const target = path.join(root, 'lang', 'mp-messages.js')
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) {
    throw new Error('Mini program locales are stale. Run node scripts/compile-mp-locales.mjs')
  }
} else {
  fs.writeFileSync(target, output)
}
